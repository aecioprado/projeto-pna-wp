<!-- wp:heading {"anchor":"quem-somos"} -->
<h2 class="wp-block-heading" id="quem-somos">Quem somos?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>No Centro Acadêmico do Agreste (CAA), em Caruaru, há o Projeto de Extensão PNA – Pets no Agreste, formado por voluntários, professores, técnicos, alunos e egressos de vários cursos. O projeto arrecada fundos, distribui rações e publica no Instagram (@petsnoagreste) informações sobre adoções no CAA – UFPE e arredores. Esta plataforma foi criada para ampliar e organizar essas ações, apresentando os pets e indicando com clareza as formas de apoiar e de adotar.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"como-adotar"} -->
<h2 class="wp-block-heading" id="como-adotar">Como realizar a adoção?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Achou seu animalzinho? Na página de pets para adoção, selecione o pet escolhido para ver mais informações sobre ele e clique em <strong>Adotar</strong>. Um formulário vai aparecer para você preencher com informações importantes para nossa equipe avaliar seu pedido. Todos os campos são obrigatórios.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Pedimos seu nome, data de nascimento (a pessoa que adota precisa ser maior de idade), telefone, CEP (para saber se você é de Caruaru ou arredores), ocupação e quantos animais você já tem, o que nos ajuda a indicar conteúdos para a adaptação do novo membro da família. Por fim, pedimos que conte um pouco sobre os motivos da adoção e que confirme o compromisso de cuidar da saúde, do bem-estar e da segurança do pet, sem nenhum tipo de maus-tratos.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"buscar-pet"} -->
<h2 class="wp-block-heading" id="buscar-pet">Como buscar o pet escolhido?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Depois que o formulário de adoção for aprovado pela nossa equipe, enviaremos uma mensagem para o seu e-mail para combinar data e horário. Para buscar seu novo pet, leve algo para transportá-lo, de preferência uma caixa de transporte. A busca é feita na universidade: Centro Acadêmico do Agreste – UFPE. Ao chegar, uma pessoa responsável vai conferir as informações e entregar o animalzinho, concluindo a adoção.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"apadrinhamento"} -->
<h2 class="wp-block-heading" id="apadrinhamento">O que é o apadrinhamento?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>É uma opção para quem não pode adotar, mas quer ajudar no cuidado dos pets. Ao se tornar padrinho ou madrinha, você faz doações mensais, que podem ser canceladas a qualquer momento. O valor é usado exclusivamente nos cuidados de saúde e alimentação do pet escolhido. Você recebe notícias do animal periodicamente e é avisado em caso de adoção, o que encerra o apadrinhamento.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Para apadrinhar, clique em <strong>Apadrinhar</strong> na página do pet e preencha o formulário com seus dados, o valor mensal e a forma de pagamento. Após a aprovação, enviaremos por e-mail as instruções para o pagamento, renovadas todo mês.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"anchor":"maus-tratos"} -->
<h2 class="wp-block-heading" id="maus-tratos">O que é maus-tratos e como combater?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Maus-tratos são atos ou omissões que causam sofrimento a um animal: agressões, abandono, falta de água, comida, abrigo ou cuidados de saúde, e manter o animal preso em espaço inadequado, entre outros. No Brasil, maus-tratos a animais são crime (Lei 9.605/1998, art. 32), com pena maior quando a vítima é um cão ou gato (Lei 14.064/2020).</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Se você presenciar maus-tratos, registre o que puder (fotos, vídeos, endereço, data) e denuncie à delegacia de polícia mais próxima ou ao Ministério Público. Nunca se coloque em risco.</p>
<!-- /wp:paragraph -->
